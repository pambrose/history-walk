/**
 * The server's version and the slide deck it serves ([masterSlides], picked at startup). BuildConfig is generated by
 * the build (see buildConfig in build.gradle.kts); only jar builds carry a real release date and build time, so a dev
 * build reports "unreleased" and a build time of 0.
 */
@Version(
  version = BuildConfig.VERSION,
  releaseDate = BuildConfig.RELEASE_DATE,
  buildTime = BuildConfig.BUILD_TIME,
)
object HistoryWalkServer {
  private val masterSlidesRef = AtomicReference(SlideDeck())

  var masterSlides: SlideDeck
    get() = masterSlidesRef.get()
    set(value) = masterSlidesRef.set(value)
}

/**
 * The server's Ktor module (`application.yaml`). It checks the settings, failing startup on a bad one, picks the slide
 * deck, installs the plugins and routes, migrates and connects to the database, brings the stored roles into line with
 * `TEACHER_EMAILS`, and registers the RPC service.
 */
fun Application.main() {
  val logger = KotlinLogging.logger {}

  logger.apply {
    info {
      getBanner(
        "banners/history-walk.txt",
        this,
      )
    }
    info { HistoryWalkServer::class.versionDesc() }
  }

  assignProperties()

  // Fails startup before anything is installed if a required sign-in setting is missing, or a setting holds a value it
  // cannot use
  verifyAuthConfig()
  verifySettings()

  // Fails startup too if SLIDES_VARIABLE_NAME names no deck, rather than serve the other walk
  val slidesName = SLIDES_VARIABLE_NAME.getEnvOrNull()
  masterSlides = slideDeckFor(slidesName)
  logger.info {
    val setting = slidesName?.let { "\"$it\"" } ?: "unset"
    "Serving the ${slideDeckName(slidesName)} slide deck (SLIDES_VARIABLE_NAME is $setting)"
  }

  installs()
  assignRoutes()

  dbmsInit(environment.config)

  // The class pages count by the stored role; bring it into line with TEACHER_EMAILS as this process reads it
  User.syncStoredRoles().also { changed ->
    if (changed > 0) logger.info { "Brought $changed stored role(s) into line with TEACHER_EMAILS" }
  }

  // The client is served by Routes.staticContent, with caching headers Kilua's own static handling does not send
  initRpc(initStaticResources = false) {
    registerService<IContentService> { call -> ContentService(call) }
  }
}
