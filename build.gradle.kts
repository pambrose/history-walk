// The build date and time come from ValueSources, which the configuration cache re-reads on every run: when a value
// differs, the cache is invalidated and the tasks that read it re-run.
abstract class CurrentDateValueSource : ValueSource<String, ValueSourceParameters.None> {
    override fun obtain(): String =
        LocalDate.now().format(DateTimeFormatter.ofPattern("MM/dd/yyyy"))
}

abstract class BuildTimeMillisValueSource : ValueSource<Long, ValueSourceParameters.None> {
    override fun obtain(): Long = System.currentTimeMillis()
}

// Only a build that packages the fat jar (one asked for `jar`, as make build, make docker-build, and Heroku do, or given
// -PstampBuildTime=true) is stamped with its build date and time. Every compile reads BuildConfig, so a stamp that
// changed on every run would make every build recompile from scratch and leave the build cache nothing to reuse.
// Unstamped builds report a release date of "unreleased" and a build time of 0.
val apiVersion = project.property("apiVersion") as String

val stampBuildTime =
    providers.gradleProperty("stampBuildTime").orNull.toBoolean() ||
        gradle.startParameter.taskNames.any { it.substringAfterLast(':') == "jar" }
val releaseDate: Provider<String> =
    if (stampBuildTime) providers.of(CurrentDateValueSource::class.java) {} else provider { "unreleased" }
val buildTime: Provider<Long> =
    if (stampBuildTime) providers.of(BuildTimeMillisValueSource::class.java) {} else provider { 0L }

// Generates <group>.BuildConfig (com.pambrose.BuildConfig) in commonMain, so both the server and the client can read it.
buildConfig {
    useKotlinOutput()
    packageName(project.group.toString())
    documentation.set("Generated by BuildConfig plugin")
    buildConfigField("String", "APP_NAME", "\"${project.name}\"")
    buildConfigField("String", "VERSION", provider { "\"${project.version}\"" })
    buildConfigField("String", "API_VERSION", "\"$apiVersion\"")
    buildConfigField("String", "RELEASE_DATE", releaseDate.map { "\"$it\"" })
    buildConfigField("long", "BUILD_TIME", buildTime.map { "${it}L" })
}

